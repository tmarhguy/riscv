# IronCore MulDiv Tests
# Verifies M extension operations

#include "test_macros.h"

RVTEST_CODE_BEGIN

#-----------------------------------------------------------------------------
# Test 1: MUL (lower 32 bits)
#-----------------------------------------------------------------------------
test_1:
    li      x1, 7
    li      x2, 6
    mul     x3, x1, x2
    TEST_CASE 1, x3, 42

#-----------------------------------------------------------------------------
# Test 2: MUL with larger numbers
#-----------------------------------------------------------------------------
test_2:
    li      x1, 1000
    li      x2, 1000
    mul     x3, x1, x2
    li      x4, 1000000
    beq     x3, x4, test_2_pass
    j       test_fail
test_2_pass:
    li      x30, 2

#-----------------------------------------------------------------------------
# Test 3: MUL negative * positive
#-----------------------------------------------------------------------------
test_3:
    li      x1, -10
    li      x2, 5
    mul     x3, x1, x2
    li      x4, -50
    beq     x3, x4, test_3_pass
    j       test_fail
test_3_pass:
    li      x30, 3

#-----------------------------------------------------------------------------
# Test 4: MUL negative * negative
#-----------------------------------------------------------------------------
test_4:
    li      x1, -10
    li      x2, -5
    mul     x3, x1, x2
    TEST_CASE 4, x3, 50

#-----------------------------------------------------------------------------
# Test 5: MULH (upper 32 bits, signed*signed)
#-----------------------------------------------------------------------------
test_5:
    li      x1, 0x80000000      # -2^31
    li      x2, 2
    mulh    x3, x1, x2          # Result should be -1 (sign-extended)
    li      x4, 0xFFFFFFFF
    beq     x3, x4, test_5_pass
    j       test_fail
test_5_pass:
    li      x30, 5

#-----------------------------------------------------------------------------
# Test 6: MULHU (upper 32 bits, unsigned*unsigned)
#-----------------------------------------------------------------------------
test_6:
    li      x1, 0x80000000      # 2^31 unsigned
    li      x2, 2
    mulhu   x3, x1, x2          # Result: (2^31 * 2) >> 32 = 1
    TEST_CASE 6, x3, 1

#-----------------------------------------------------------------------------
# Test 7: MULHSU (upper 32 bits, signed*unsigned)
#-----------------------------------------------------------------------------
test_7:
    li      x1, -1              # Signed -1
    li      x2, 2               # Unsigned 2
    mulhsu  x3, x1, x2          # (-1 * 2) >> 32 = -1
    li      x4, 0xFFFFFFFF
    beq     x3, x4, test_7_pass
    j       test_fail
test_7_pass:
    li      x30, 7

#-----------------------------------------------------------------------------
# Test 8: DIV (signed division)
#-----------------------------------------------------------------------------
test_8:
    li      x1, 100
    li      x2, 10
    div     x3, x1, x2
    TEST_CASE 8, x3, 10

#-----------------------------------------------------------------------------
# Test 9: DIV negative
#-----------------------------------------------------------------------------
test_9:
    li      x1, -100
    li      x2, 10
    div     x3, x1, x2
    li      x4, -10
    beq     x3, x4, test_9_pass
    j       test_fail
test_9_pass:
    li      x30, 9

#-----------------------------------------------------------------------------
# Test 10: DIVU (unsigned division)
#-----------------------------------------------------------------------------
test_10:
    li      x1, 100
    li      x2, 7
    divu    x3, x1, x2          # 100 / 7 = 14
    TEST_CASE 10, x3, 14

#-----------------------------------------------------------------------------
# Test 11: REM (signed remainder)
#-----------------------------------------------------------------------------
test_11:
    li      x1, 100
    li      x2, 7
    rem     x3, x1, x2          # 100 % 7 = 2
    TEST_CASE 11, x3, 2

#-----------------------------------------------------------------------------
# Test 12: REM negative dividend
#-----------------------------------------------------------------------------
test_12:
    li      x1, -100
    li      x2, 7
    rem     x3, x1, x2          # -100 % 7 = -2 (sign of dividend)
    li      x4, -2
    beq     x3, x4, test_12_pass
    j       test_fail
test_12_pass:
    li      x30, 12

#-----------------------------------------------------------------------------
# Test 13: REMU (unsigned remainder)
#-----------------------------------------------------------------------------
test_13:
    li      x1, 100
    li      x2, 7
    remu    x3, x1, x2          # 100 % 7 = 2
    TEST_CASE 13, x3, 2

#-----------------------------------------------------------------------------
# Test 14: Division by zero (DIV)
# RISC-V spec: x / 0 = -1 (all ones)
#-----------------------------------------------------------------------------
test_14:
    li      x1, 42
    li      x2, 0
    div     x3, x1, x2
    li      x4, 0xFFFFFFFF      # -1
    beq     x3, x4, test_14_pass
    j       test_fail
test_14_pass:
    li      x30, 14

#-----------------------------------------------------------------------------
# Test 15: Division by zero (DIVU)
# RISC-V spec: x /u 0 = 2^32 - 1 (max unsigned)
#-----------------------------------------------------------------------------
test_15:
    li      x1, 42
    li      x2, 0
    divu    x3, x1, x2
    li      x4, 0xFFFFFFFF
    beq     x3, x4, test_15_pass
    j       test_fail
test_15_pass:
    li      x30, 15

#-----------------------------------------------------------------------------
# Test 16: Remainder by zero (REM)
# RISC-V spec: x % 0 = x
#-----------------------------------------------------------------------------
test_16:
    li      x1, 42
    li      x2, 0
    rem     x3, x1, x2
    TEST_CASE 16, x3, 42

#-----------------------------------------------------------------------------
# Test 17: Remainder by zero (REMU)
#-----------------------------------------------------------------------------
test_17:
    li      x1, 42
    li      x2, 0
    remu    x3, x1, x2
    TEST_CASE 17, x3, 42

#-----------------------------------------------------------------------------
# Test 18: Signed overflow (-2^31 / -1)
# RISC-V spec: overflow result = -2^31
#-----------------------------------------------------------------------------
test_18:
    li      x1, 0x80000000      # -2^31
    li      x2, -1
    div     x3, x1, x2          # Overflow case
    li      x4, 0x80000000      # Result is -2^31
    beq     x3, x4, test_18_pass
    j       test_fail
test_18_pass:
    li      x30, 18

#-----------------------------------------------------------------------------
# Test 19: MUL result used immediately (stall test)
#-----------------------------------------------------------------------------
test_19:
    li      x1, 5
    li      x2, 5
    mul     x3, x1, x2          # x3 = 25
    addi    x4, x3, 5           # Use immediately - must stall
    TEST_CASE 19, x4, 30

#-----------------------------------------------------------------------------
# Test 20: DIV result used immediately (stall test)
#-----------------------------------------------------------------------------
test_20:
    li      x1, 100
    li      x2, 4
    div     x3, x1, x2          # x3 = 25
    addi    x4, x3, 5           # Use immediately - must stall ~32 cycles
    TEST_CASE 20, x4, 30

RVTEST_CODE_END
