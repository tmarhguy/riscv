# IronCore ALU Tests
# Verifies all ALU operations

#include "test_macros.h"

RVTEST_CODE_BEGIN

#-----------------------------------------------------------------------------
# Test 1: ADD
#-----------------------------------------------------------------------------
test_1:
    li      x1, 100
    li      x2, 200
    add     x3, x1, x2
    TEST_CASE 1, x3, 300

#-----------------------------------------------------------------------------
# Test 2: ADD with overflow
#-----------------------------------------------------------------------------
test_2:
    li      x1, 0x7FFFFFFF      # Max positive
    li      x2, 1
    add     x3, x1, x2          # Overflow to 0x80000000
    li      x4, 0x80000000
    beq     x3, x4, test_2_pass
    j       test_fail
test_2_pass:
    li      x30, 2

#-----------------------------------------------------------------------------
# Test 3: SUB
#-----------------------------------------------------------------------------
test_3:
    li      x1, 500
    li      x2, 123
    sub     x3, x1, x2
    TEST_CASE 3, x3, 377

#-----------------------------------------------------------------------------
# Test 4: SUB with underflow
#-----------------------------------------------------------------------------
test_4:
    li      x1, 0
    li      x2, 1
    sub     x3, x1, x2          # 0 - 1 = -1 (0xFFFFFFFF)
    li      x4, 0xFFFFFFFF
    beq     x3, x4, test_4_pass
    j       test_fail
test_4_pass:
    li      x30, 4

#-----------------------------------------------------------------------------
# Test 5: AND
#-----------------------------------------------------------------------------
test_5:
    li      x1, 0xFF00FF00
    li      x2, 0x0F0F0F0F
    and     x3, x1, x2
    li      x4, 0x0F000F00
    beq     x3, x4, test_5_pass
    j       test_fail
test_5_pass:
    li      x30, 5

#-----------------------------------------------------------------------------
# Test 6: OR
#-----------------------------------------------------------------------------
test_6:
    li      x1, 0xFF00FF00
    li      x2, 0x00FF00FF
    or      x3, x1, x2
    li      x4, 0xFFFFFFFF
    beq     x3, x4, test_6_pass
    j       test_fail
test_6_pass:
    li      x30, 6

#-----------------------------------------------------------------------------
# Test 7: XOR
#-----------------------------------------------------------------------------
test_7:
    li      x1, 0xAAAAAAAA
    li      x2, 0x55555555
    xor     x3, x1, x2
    li      x4, 0xFFFFFFFF
    beq     x3, x4, test_7_pass
    j       test_fail
test_7_pass:
    li      x30, 7

#-----------------------------------------------------------------------------
# Test 8: SLL (shift left logical)
#-----------------------------------------------------------------------------
test_8:
    li      x1, 1
    li      x2, 16
    sll     x3, x1, x2          # 1 << 16 = 0x10000
    li      x4, 0x10000
    beq     x3, x4, test_8_pass
    j       test_fail
test_8_pass:
    li      x30, 8

#-----------------------------------------------------------------------------
# Test 9: SRL (shift right logical)
#-----------------------------------------------------------------------------
test_9:
    li      x1, 0x80000000
    li      x2, 16
    srl     x3, x1, x2          # 0x80000000 >> 16 = 0x8000
    li      x4, 0x8000
    beq     x3, x4, test_9_pass
    j       test_fail
test_9_pass:
    li      x30, 9

#-----------------------------------------------------------------------------
# Test 10: SRA (shift right arithmetic)
#-----------------------------------------------------------------------------
test_10:
    li      x1, 0x80000000      # Negative number
    li      x2, 16
    sra     x3, x1, x2          # Sign-extended: 0xFFFF8000
    li      x4, 0xFFFF8000
    beq     x3, x4, test_10_pass
    j       test_fail
test_10_pass:
    li      x30, 10

#-----------------------------------------------------------------------------
# Test 11: SLT (set less than, signed)
#-----------------------------------------------------------------------------
test_11:
    li      x1, -5
    li      x2, 5
    slt     x3, x1, x2          # -5 < 5 (signed) = 1
    TEST_CASE 11, x3, 1

test_11b:
    li      x1, 5
    li      x2, -5
    slt     x3, x1, x2          # 5 < -5 (signed) = 0
    li      x4, 0
    beq     x3, x4, test_11b_pass
    j       test_fail
test_11b_pass:
    li      x30, 11

#-----------------------------------------------------------------------------
# Test 12: SLTU (set less than, unsigned)
#-----------------------------------------------------------------------------
test_12:
    li      x1, 5
    li      x2, 0xFFFFFFFF      # Max unsigned
    sltu    x3, x1, x2          # 5 < MAX (unsigned) = 1
    TEST_CASE 12, x3, 1

test_12b:
    li      x1, 0xFFFFFFFF
    li      x2, 5
    sltu    x3, x1, x2          # MAX < 5 (unsigned) = 0
    li      x4, 0
    beq     x3, x4, test_12b_pass
    j       test_fail
test_12b_pass:
    li      x30, 12

#-----------------------------------------------------------------------------
# Test 13: ADDI
#-----------------------------------------------------------------------------
test_13:
    li      x1, 100
    addi    x2, x1, 50
    TEST_CASE 13, x2, 150

#-----------------------------------------------------------------------------
# Test 14: ADDI negative
#-----------------------------------------------------------------------------
test_14:
    li      x1, 100
    addi    x2, x1, -30
    TEST_CASE 14, x2, 70

#-----------------------------------------------------------------------------
# Test 15: ANDI
#-----------------------------------------------------------------------------
test_15:
    li      x1, 0xFFFFFFFF
    andi    x2, x1, 0x0FF       # Only lower 12 bits
    li      x3, 0xFF
    beq     x2, x3, test_15_pass
    j       test_fail
test_15_pass:
    li      x30, 15

#-----------------------------------------------------------------------------
# Test 16: ORI
#-----------------------------------------------------------------------------
test_16:
    li      x1, 0x00000000
    ori     x2, x1, 0x123
    li      x3, 0x123
    beq     x2, x3, test_16_pass
    j       test_fail
test_16_pass:
    li      x30, 16

#-----------------------------------------------------------------------------
# Test 17: XORI
#-----------------------------------------------------------------------------
test_17:
    li      x1, 0xFFFFFFFF
    xori    x2, x1, 0xFF        # Invert lower bits
    li      x3, 0xFFFFFF00
    beq     x2, x3, test_17_pass
    j       test_fail
test_17_pass:
    li      x30, 17

#-----------------------------------------------------------------------------
# Test 18: SLLI
#-----------------------------------------------------------------------------
test_18:
    li      x1, 0x00000001
    slli    x2, x1, 31
    li      x3, 0x80000000
    beq     x2, x3, test_18_pass
    j       test_fail
test_18_pass:
    li      x30, 18

#-----------------------------------------------------------------------------
# Test 19: SRLI
#-----------------------------------------------------------------------------
test_19:
    li      x1, 0x80000000
    srli    x2, x1, 31
    li      x3, 1
    beq     x2, x3, test_19_pass
    j       test_fail
test_19_pass:
    li      x30, 19

#-----------------------------------------------------------------------------
# Test 20: SRAI
#-----------------------------------------------------------------------------
test_20:
    li      x1, 0x80000000
    srai    x2, x1, 4
    li      x3, 0xF8000000      # Sign-extended
    beq     x2, x3, test_20_pass
    j       test_fail
test_20_pass:
    li      x30, 20

#-----------------------------------------------------------------------------
# Test 21: SLTI
#-----------------------------------------------------------------------------
test_21:
    li      x1, -10
    slti    x2, x1, 0           # -10 < 0 = 1
    TEST_CASE 21, x2, 1

#-----------------------------------------------------------------------------
# Test 22: SLTIU
#-----------------------------------------------------------------------------
test_22:
    li      x1, 0xFFFFFFFF
    sltiu   x2, x1, 1           # MAX < 1 (unsigned) = 0
    TEST_CASE 22, x2, 0

#-----------------------------------------------------------------------------
# Test 23: LUI
#-----------------------------------------------------------------------------
test_23:
    lui     x1, 0x12345
    li      x2, 0x12345000
    beq     x1, x2, test_23_pass
    j       test_fail
test_23_pass:
    li      x30, 23

#-----------------------------------------------------------------------------
# Test 24: AUIPC
#-----------------------------------------------------------------------------
test_24:
    auipc   x1, 0               # x1 = PC
    la      x2, test_24         # x2 = address of test_24
    beq     x1, x2, test_24_pass
    j       test_fail
test_24_pass:
    li      x30, 24

RVTEST_CODE_END
